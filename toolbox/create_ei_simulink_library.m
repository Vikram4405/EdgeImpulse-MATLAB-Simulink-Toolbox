% create_ei_simulink_library.m
% Creates the drag-and-drop Simulink Library 'EdgeImpulse_Library.slx'
% containing BOTH flat (no-subsystem) blocks:
%   1. 'EI_Data_Logger' (Plugin 1: Collects & uploads training signals to Edge Impulse)
%   2. 'EI_Classifier'  (Plugin 2: Runs trained Edge Impulse C++ models live in Simulink)

fprintf('=== Creating Drag-and-Drop Simulink Library: EdgeImpulse_Library.slx ===\n');

tbxDir = fileparts(mfilename('fullpath'));
if isempty(tbxDir)
    tbxDir = pwd;
end
addpath(tbxDir);

libName = 'EdgeImpulse_Library';
if bdIsLoaded(libName)
    close_system(libName, 0);
end

% Create new Simulink Library
new_system(libName, 'Library');
set_param(libName, 'Lock', 'off');

% =========================================================================
% BLOCK 1: 'EI_Data_Logger' (Plugin 1: Input Signal -> Edge Impulse Cloud)
% =========================================================================
blkPath = [libName '/EI_Data_Logger'];
add_block('simulink/User-Defined Functions/Level-2 MATLAB S-Function', blkPath, ...
    'FunctionName', 'ei_logger_msfun', ...
    'Position', [50, 50, 260, 140]);

maskObj = Simulink.Mask.create(blkPath);
maskObj.Description = ['Edge Impulse Universal Data Logger & Cloud Uploader (Plugin 1).' newline ...
    'Drag an output arrow from ANY block in your Simulink system into this block ' ...
    '(supports 1-axis Waveform/Temp, 3-axis Accel, 6-axis IMU, etc.). ' ...
    'Inherits the input sample rate automatically, collects fixed windows ' ...
    '(e.g. 5s or 10s), and uploads directly to Edge Impulse Studio.'];

maskObj.addParameter('Type', 'checkbox', 'Name', 'ei_enabled', ...
    'Prompt', 'Enable Logging / Cloud Upload', ...
    'Value', 'on', 'Evaluate', 'off');

maskObj.addParameter('Type', 'checkbox', 'Name', 'ei_skip_zero', ...
    'Prompt', 'Skip All-Zero / Unconnected Signals (safety guard)', ...
    'Value', 'on', 'Evaluate', 'off');

maskObj.addParameter('Type', 'edit', 'Name', 'ei_label', ...
    'Prompt', 'Label Name (e.g. Sine_Wave, Square_Wave, healthy):', ...
    'Value', 'healthy', 'Evaluate', 'off');

maskObj.addParameter('Type', 'edit', 'Name', 'ei_window_sec', ...
    'Prompt', 'Sampling Window Size in Seconds (e.g. 5 or 10):', ...
    'Value', '10', 'Evaluate', 'off');

maskObj.addParameter('Type', 'edit', 'Name', 'ei_max_chunks', ...
    'Prompt', 'Max Windows to Upload per Run (0 = unlimited):', ...
    'Value', '10', 'Evaluate', 'off');

maskObj.addParameter('Type', 'popup', 'Name', 'ei_category', ...
    'Prompt', 'Dataset Split (training / testing / split = auto 80/20):', ...
    'TypeOptions', {'training', 'testing', 'split'}, ...
    'Value', 'training', 'Evaluate', 'off');

maskObj.addParameter('Type', 'edit', 'Name', 'ei_sensors', ...
    'Prompt', 'Sensor Channel Names (comma-separated, or auto):', ...
    'Value', 'auto', 'Evaluate', 'off');

maskObj.addParameter('Type', 'edit', 'Name', 'ei_units', ...
    'Prompt', 'Sensor Units (comma-separated, or auto):', ...
    'Value', 'auto', 'Evaluate', 'off');

maskObj.addParameter('Type', 'edit', 'Name', 'ei_apikey', ...
    'Prompt', 'Edge Impulse API Key (ei_... for live upload, or leave blank for local):', ...
    'Value', '', 'Evaluate', 'off');

maskObj.addParameter('Type', 'edit', 'Name', 'ei_outdir', ...
    'Prompt', 'Local Export Folder (or default):', ...
    'Value', 'default', 'Evaluate', 'off');

maskObj.Display = [ ...
    'color(''blue'');' newline ...
    'disp([''EI Data Logger (Plugin 1)\nLabel: '' ei_label ''\nWindow: '' ei_window_sec ''s ['' ei_category '']'']);' ...
];

% =========================================================================
% BLOCK 2: 'EI_Model' (Plugin 2: Trained Edge Impulse Model -> Live Inference)
% =========================================================================
clsPath = [libName '/EI_Model'];
add_block('simulink/User-Defined Functions/Level-2 MATLAB S-Function', clsPath, ...
    'FunctionName', 'ei_classifier_msfun', ...
    'Position', [320, 50, 560, 140]);

clsMask = Simulink.Mask.create(clsPath);
clsMask.Description = ['Edge Impulse Universal Live Model (Plugin 2).' newline ...
    'Supports Classification, Regression, Anomaly Detection (K-means/GMM), and Object Detection (FOMO/YOLO).' newline ...
    'Click "Browse & Build Edge Impulse .ZIP Model..." below (or paste your .zip path) ' ...
    'to automatically extract, compile, and configure any Edge Impulse C++ library!' newline ...
    'When you click Run in Simulink, a Live Prediction Monitor Window pops up showing ' ...
    'the predicted TEXT LABEL, confidence percentage, and class probability bars!'];

try
    clsMask.addDialogControl('Type', 'pushbutton', 'Name', 'btn_browse_zip', ...
        'Prompt', '  Browse & Build Edge Impulse .ZIP Model...  ', ...
        'Callback', 'ei_browse_and_import_callback(gcbh);');
catch
end

clsMask.addParameter('Type', 'edit', 'Name', 'ei_zip_path', ...
    'Prompt', 'Edge Impulse C++ .ZIP File Path (auto-compiles if new):', ...
    'Value', '', 'Evaluate', 'off');

clsMask.addParameter('Type', 'checkbox', 'Name', 'ei_show_hud', ...
    'Prompt', 'Show Live Prediction Monitor Window (Text Label + Probability Bars)', ...
    'Value', 'on', 'Evaluate', 'off');

clsMask.addParameter('Type', 'checkbox', 'Name', 'ei_verbose', ...
    'Prompt', 'Print Live Predictions in MATLAB Command Window', ...
    'Value', 'on', 'Evaluate', 'off');

clsMask.addParameter('Type', 'edit', 'Name', 'ei_step_sec', ...
    'Prompt', 'Inference Update Interval in Seconds (e.g. 0.25 = run every 250ms):', ...
    'Value', '0.25', 'Evaluate', 'off');

clsMask.Display = [ ...
    'color(''darkGreen'');' newline ...
    'port_label(''input'', 1, ''Signal_In'');' newline ...
    'port_label(''output'', 1, ''Class_ID'');' newline ...
    'port_label(''output'', 2, ''Confidence'');' newline ...
    'port_label(''output'', 3, ''Scores'');' newline ...
    'disp(''EI Model\n(Plugin 2)'');' ...
];

% Save Library
libFile = fullfile(tbxDir, [libName '.slx']);
save_system(libName, libFile);
close_system(libName);

fprintf('SUCCESS: Created %s with [EI_Data_Logger] and [EI_Model]!\n', libFile);
